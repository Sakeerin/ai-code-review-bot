import { z } from 'zod'
import { stringify } from 'yaml'
import { generateObjectWithFallback } from './providers'

export interface RepoFileSample {
  path: string
  content: string
}

const GeneratedProfileSchema = z.object({
  profile: z
    .string()
    .describe("Built-in profile: 'typescript', 'laravel', 'vue', or 'laravel-vue'"),
  language: z.string().describe("ISO language code for review comments, e.g. 'en' or 'th'"),
  rules: z
    .array(
      z.object({
        id: z.string().describe('Kebab-case rule identifier'),
        severity: z.enum(['bug', 'suggestion', 'nitpick', 'praise']),
        message: z.string().describe('Short rule description shown in review comment'),
      }),
    )
    .describe('Custom rules detected from the codebase patterns'),
  ignore: z.array(z.string()).describe('Glob patterns for files to skip'),
  limits: z.object({
    max_file_size_lines: z.number().int().min(100).max(2000),
    max_files_per_pr: z.number().int().min(5).max(50),
  }),
  reasoning: z.string().describe('Brief explanation of why these rules were chosen'),
})

export type GeneratedProfile = z.infer<typeof GeneratedProfileSchema>

/**
 * Analyze a sample of repository files and generate a tailored .reviewbot.yml config.
 * Returns both the structured profile and the YAML string.
 */
export async function generateConventionProfile(
  files: RepoFileSample[],
  repoFullName: string,
): Promise<{ profile: GeneratedProfile; yaml: string }> {
  const fileSummary = files
    .slice(0, 20) // cap tokens
    .map((f) => `### ${f.path}\n\`\`\`\n${f.content.slice(0, 800)}\n\`\`\``)
    .join('\n\n')

  const { object } = await generateObjectWithFallback<GeneratedProfile>({
    schema: GeneratedProfileSchema,
    system: `You are an expert code convention analyzer.
Analyze the provided code samples from the repository "${repoFullName}" and generate a .reviewbot.yml configuration.

Detect:
- Primary framework/language (Laravel, Vue.js, TypeScript, React, etc.)
- Common anti-patterns visible in the code
- Files or directories that should be ignored in reviews (migrations, generated code, tests)
- Appropriate review scope limits based on apparent project size

Output practical, actionable rules that match the patterns you actually see in the code.
Keep rules focused on issues that would cause real problems, not style preferences.`,
    prompt: `Repository: ${repoFullName}\n\nFile samples:\n\n${fileSummary}`,
  })

  const profile = GeneratedProfileSchema.parse(object)
  return { profile, yaml: buildYaml(profile) }
}

export function buildYaml(p: GeneratedProfile): string {
  return (
    '# Generated by AI Review Bot. Customize for your team.\n' +
    stringify({
      version: 1,
      profile: p.profile,
      language: p.language,
      rules: p.rules,
      ignore: p.ignore,
      limits: p.limits,
    })
  )
}
